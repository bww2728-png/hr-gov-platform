let current = localStorage.getItem('hr_lang') || 'ar';

export function setLang(lang) {
  current = lang;
  localStorage.setItem('hr_lang', lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'en' ? 'ltr' : 'rtl';
  window.dispatchEvent(new CustomEvent('hr:lang', { detail: lang }));
}

export function getLang() { return current; }

export function t(key, fallback) {
  return dict[current]?.[key] || dict.ar[key] || fallback || key;
}

export function useT() {
  const [, force] = React.useState(0);
  React.useEffect(() => {
    const h = () => force((x) => x + 1);
    window.addEventListener('hr:lang', h);
    return () => window.removeEventListener('hr:lang', h);
  }, []);
  return t;
}

